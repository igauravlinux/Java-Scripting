
// String Methods

let str = "Gaurav";
let str1 = "Kumar";

console.log(str.length); // Gets number of Character

console.log(str.toUpperCase()); // Converts to uppercase

console.log(str.toLowerCase()); // Converts to lowercase

console.log(str.charAt(0)); // Gets Character at Index

console.log(str.slice(2 , 5)); // Gets part of the string

console.log(str.substring(2 , 5)); // Similar to slice but not negatives

console.log(str.replace("G","K")); // Replace part of string

console.log(str.trim()); // Removes whitespaces

console.log(str.split(",")); // //Converts string to array

console.log(str.concat(str1)); // Joins two strings

console.log(str.includes("G")); // Checks if the string contains a substring

console.log(str.startsWith("Gau")); // checks if string starts with given text

console.log(str.endsWith("v")); // Checks if string ends with given text

console.log(str.repeat(3)); // Repeats string n times









